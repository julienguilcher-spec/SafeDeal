/** Emprise de la Conciergerie dans ce repère (un peu élargie vers le quai) : retranchée du palais. */
export const ZONE_CONCIERGERIE: readonly number[] = [47.9, -23.1, 58.3, 104.5, 114, 98, 114, -29];
/** Cour du Mai (boulevard du Palais) : bornes de la cour et plan de la grille. */
export const COUR_MAI = { x0: 4.9, x1: 41.7, z0: 72.2, grille: 104.3 } as const;
/** Cour de la Sainte-Chapelle (la chapelle est un autre monument). */
export const COUR_SAINTE_CHAPELLE = { x0: -49.4, x1: -2.9, z0: 9.1, z1: 92.7 } as const;

/** Emprise du palais sans la Conciergerie. */
export function palaisRing(ring: ArrayLike<number>): number[] {
  const pieces = solidsMinus(ring, [ZONE_CONCIERGERIE as number[]], 50);
  let best = pieces[0] ?? Array.from(ring);
  for (const q of pieces) if (signedArea(q) > signedArea(best)) best = q;
  return best;
}

export function colliders(site: MonumentSite): MonumentCollider[] {
  const p = planOf(site, EMPRISE);
  const C = COUR_SAINTE_CHAPELLE, M = COUR_MAI;
  const solids = solidsMinus(palaisRing(p.ring), [rectOf(C.x0 + 0.4, C.z0 + 0.4, C.x1 - 0.4, C.z1 - 0.4)], 4);
  const out: MonumentCollider[] = solids.map((r) => solid(r, H_FAITE));
  out.push(solid(rectOf(M.x0, M.grille - 0.3, M.x1, M.grille + 0.3), 6.5));
  out.push(solid(rectOf(M.x0 + 6, M.z0, M.x1 - 6, M.z0 + 9), 4));
  return collidersToLocal(p, out);
}
